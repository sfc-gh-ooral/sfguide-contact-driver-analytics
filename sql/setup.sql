-- Deterministic integer hash, identical to synHash() in lib/synthetic.ts.
CREATE OR REPLACE FUNCTION SYN_XS(H NUMBER, S NUMBER) RETURNS NUMBER AS 'BITXOR(H, BITSHIFTRIGHT(H, S))';
CREATE OR REPLACE FUNCTION SYN_HASH(I NUMBER, K NUMBER) RETURNS NUMBER AS
$$ SYN_XS(MOD(SYN_XS(MOD(SYN_XS(MOD(I * 2654435761 + K * 40503 + 12345, 4294967296), 16) * 2246822507, 4294967296), 13) * 3266489909, 4294967296), 16) $$;
-- Uniform integer in [0, N), using exact integer division.
CREATE OR REPLACE FUNCTION SYN_IDX(I NUMBER, K NUMBER, N NUMBER) RETURNS NUMBER(38, 0) AS
$$ (SYN_HASH(I, K) * N - MOD(SYN_HASH(I, K) * N, 4294967296)) / 4294967296 $$;

-- 13 weeks of calls starting 2026-08-17, same rules as generateCalls() in lib/synthetic.ts.
CREATE OR REPLACE TABLE CALLS COMMENT = 'Synthetic call log (no transcript text)' AS
WITH slots AS (
  SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS i FROM TABLE(GENERATOR(ROWCOUNT => 3510))
), kept AS (
  SELECT i, FLOOR(i / 270) AS w FROM slots
  WHERE MOD(i, 270) < 170 + SYN_IDX(100000 + FLOOR(i / 270), 1, 60) + 3 * FLOOR(i / 270)
), picked AS (
  SELECT i, w, IFF(SYN_IDX(i, 5, 1000) < 50 + 10 * w, 3, SYN_IDX(i, 6, 10)) AS t FROM kept
), shaped AS (
  SELECT i, w, t,
         IFF(SYN_IDX(i, 7, 1000) < 700, ARRAY_CONSTRUCT(4, 0, 3, 3, 4, 0, 2, 1, 1, 3)[t]::INT, SYN_IDX(i, 8, 5)) AS lob,
         SYN_IDX(i, 12, 1000) < ARRAY_CONSTRUCT(30, 60, 30, 180, 300, 80, 40, 30, 650, 40)[t]::INT AS escalated,
         SYN_IDX(i, 13, 1000) AS d
  FROM picked
)
SELECT 'CALL-' || LPAD(i, 6, '0') AS CALL_ID,
       DATEADD(day, 7 * w + SYN_IDX(i, 2, 7), '2026-08-17'::DATE) AS CALL_DATE,
       TIME_FROM_PARTS(8 + SYN_IDX(i, 3, 10), SYN_IDX(i, 4, 60), 0) AS CALL_TIME,
       ARRAY_CONSTRUCT(659, 761, 823, 882, 814, 821, 871, 943, 977, 857)[t]::INT + SYN_IDX(i, 14, 240) - 60 AS DURATION_SECONDS,
       ARRAY_CONSTRUCT('Retirement Services', 'Investment Products', 'Insurance Solutions', 'Advisory Services', 'Brokerage Operations')[lob]::VARCHAR AS LINE_OF_BUSINESS,
       ARRAY_CONSTRUCT('IRA/401k', 'Mutual Funds', 'Annuities', 'Life Insurance', 'Fee-Based Advisory', 'Trading/Execution')[ARRAY_CONSTRUCT(ARRAY_CONSTRUCT(0, 1), ARRAY_CONSTRUCT(1, 5), ARRAY_CONSTRUCT(2, 3), ARRAY_CONSTRUCT(4, 1), ARRAY_CONSTRUCT(5, 0))[lob][SYN_IDX(i, 9, 2)]::INT]::VARCHAR AS PRODUCT_CATEGORY,
       ARRAY_CONSTRUCT('High Net Worth', 'Mass Affluent', 'Emerging Affluent', 'General')[SYN_IDX(i, 10, 4)]::VARCHAR AS CUSTOMER_SEGMENT,
       ARRAY_CONSTRUCT('Advisor', 'Client', 'Branch Staff')[SYN_IDX(i, 11, 3)]::VARCHAR AS CALLER_TYPE,
       CASE WHEN escalated THEN 'Escalated' WHEN d < 700 THEN 'Resolved' WHEN d < 900 THEN 'Follow-up Required' ELSE 'Transferred' END AS CALL_DISPOSITION,
       t::INT AS TEMPLATE_ID,
       escalated AS ESCALATED
FROM shaped;
