CREATE OR REPLACE TABLE CALL_TRANSCRIPTS COMMENT = 'One row per call, with Cortex AI enrichment' AS
SELECT c.CALL_ID, c.CALL_DATE, c.CALL_TIME, c.DURATION_SECONDS,
       c.LINE_OF_BUSINESS, c.PRODUCT_CATEGORY, c.CUSTOMER_SEGMENT, c.CALLER_TYPE,
       c.CALL_DISPOSITION, t.CALL_REASON, t.TRANSCRIPT,
       a.SENTIMENT_SCORE, a.AI_SUMMARY, a.AI_DRIVER, c.ESCALATED
FROM CALLS c
JOIN TRANSCRIPT_TEMPLATES t ON t.TEMPLATE_ID = c.TEMPLATE_ID
JOIN TRANSCRIPT_AI a ON a.TEMPLATE_ID = c.TEMPLATE_ID;

-- Weeks start on Monday regardless of the WEEK_START parameter.
CREATE OR REPLACE VIEW V_CALL_DRIVER_ANALYSIS COMMENT = 'Weekly call drivers by line of business, product, segment, and caller type' AS
SELECT DATEADD(day, 1 - DAYOFWEEKISO(CALL_DATE), CALL_DATE) AS WEEK_START,
       LINE_OF_BUSINESS, PRODUCT_CATEGORY, CUSTOMER_SEGMENT, CALLER_TYPE,
       COUNT(*)                                   AS CALL_VOLUME,
       SUM(DURATION_SECONDS)                      AS TOTAL_DURATION,
       AVG(DURATION_SECONDS)                      AS AVG_DURATION,
       SUM(SENTIMENT_SCORE)                       AS SENTIMENT_SUM,
       AVG(SENTIMENT_SCORE)                       AS AVG_SENTIMENT,
       COUNT_IF(ESCALATED)                        AS ESCALATIONS,
       COUNT_IF(CALL_DISPOSITION = 'Resolved')    AS RESOLVED,
       COUNT_IF(CALL_DISPOSITION = 'Resolved') * 100 / COUNT(*) AS RESOLUTION_RATE
FROM CALL_TRANSCRIPTS
GROUP BY ALL;

CREATE OR REPLACE VIEW V_TREND_SUMMARY COMMENT = 'Weekly call volume, sentiment, escalations, and duration' AS
SELECT DATEADD(day, 1 - DAYOFWEEKISO(CALL_DATE), CALL_DATE) AS WEEK_START,
       COUNT(*)                                AS TOTAL_CALLS,
       AVG(SENTIMENT_SCORE)                    AS OVERALL_SENTIMENT,
       COUNT_IF(ESCALATED)                     AS TOTAL_ESCALATIONS,
       COUNT_IF(ESCALATED) * 100 / COUNT(*)    AS ESCALATION_RATE,
       AVG(DURATION_SECONDS)                   AS AVG_CALL_DURATION_SEC
FROM CALL_TRANSCRIPTS
GROUP BY ALL;

