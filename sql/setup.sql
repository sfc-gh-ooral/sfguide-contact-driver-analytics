-- -----------------------------------------------------------------------------
-- 4. Cortex AI enrichment, once per distinct transcript (10 rows)
--    Every call reuses one of 10 templates, so scoring each template once gives
--    the same result as scoring every call, at a fraction of the cost.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE TABLE TRANSCRIPT_AI COMMENT = 'Cortex AI outputs per transcript template' AS
SELECT
  TEMPLATE_ID,
  -- Sentiment score from -1 (negative) to 1 (positive).
  SNOWFLAKE.CORTEX.SENTIMENT(TRANSCRIPT) AS SENTIMENT_SCORE,
  -- Two-sentence supervisor summary.
  AI_COMPLETE(
    'llama3.3-70b',
    'Summarize this contact-center call for a supervisor in at most two sentences: what the caller needed and how the call ended. '
      || 'Do not include names, account numbers, or other personal details. Reply with the summary only.\n\n' || TRANSCRIPT,
    {'temperature': 0, 'max_tokens': 120}
  )::VARCHAR AS AI_SUMMARY,
  -- Contact driver category.
  AI_CLASSIFY(
    TRANSCRIPT,
    ['Account servicing', 'Money movement', 'Fees and pricing', 'Digital access issue', 'Service complaint', 'Advice and planning'],
    {'task_description': 'Classify the main reason a customer called a financial services contact center'}
  ):labels[0]::VARCHAR AS AI_DRIVER
FROM TRANSCRIPT_TEMPLATES;

