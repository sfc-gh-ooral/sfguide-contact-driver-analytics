// Regenerates the data block of sql/setup.sql (between the GENERATED markers) from
// lib/synthetic.ts and lib/transcript-templates.ts, so live mode loads the same calls
// as sample mode. Run with: npm run generate-sql   (Node 22.18+ for .ts imports)
import { readFileSync, writeFileSync } from "node:fs";
import * as syn from "../lib/synthetic.ts";
import { TRANSCRIPT_TEMPLATES } from "../lib/transcript-templates.ts";

const FILE = "sql/setup.sql";
const BEGIN = "-- >>> GENERATED by scripts/generate-sql.mjs (do not edit by hand)";
const END = "-- <<< GENERATED";

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const arr = (xs) => `ARRAY_CONSTRUCT(${xs.map((x) => (typeof x === "string" ? q(x) : x)).join(", ")})`;
const base = syn.templateBaseDurations(TRANSCRIPT_TEMPLATES.map((t) => t.transcript));

for (const t of TRANSCRIPT_TEMPLATES) if (t.transcript.includes("$$")) throw new Error("transcript contains $$");

const templates = TRANSCRIPT_TEMPLATES.map(
  (t, i) => `  (${i}, ${q(t.reason)}, $$${t.transcript}$$)`,
).join(",\n");

const block = `${BEGIN}
-- Ten fictional transcript templates (Northwind Financial is not a real firm).
CREATE OR REPLACE TABLE TRANSCRIPT_TEMPLATES (TEMPLATE_ID INT, CALL_REASON VARCHAR, TRANSCRIPT VARCHAR)
  COMMENT = 'Synthetic call transcript templates';
INSERT INTO TRANSCRIPT_TEMPLATES (TEMPLATE_ID, CALL_REASON, TRANSCRIPT) VALUES
${templates};

-- Deterministic integer hash, identical to synHash() in lib/synthetic.ts.
CREATE OR REPLACE FUNCTION SYN_XS(H NUMBER, S NUMBER) RETURNS NUMBER AS 'BITXOR(H, BITSHIFTRIGHT(H, S))';
CREATE OR REPLACE FUNCTION SYN_HASH(I NUMBER, K NUMBER) RETURNS NUMBER AS
$$ SYN_XS(MOD(SYN_XS(MOD(SYN_XS(MOD(I * 2654435761 + K * 40503 + 12345, 4294967296), 16) * 2246822507, 4294967296), 13) * 3266489909, 4294967296), 16) $$;
-- Uniform integer in [0, N), using exact integer division.
CREATE OR REPLACE FUNCTION SYN_IDX(I NUMBER, K NUMBER, N NUMBER) RETURNS NUMBER(38, 0) AS
$$ (SYN_HASH(I, K) * N - MOD(SYN_HASH(I, K) * N, 4294967296)) / 4294967296 $$;

-- ${syn.WEEKS} weeks of calls starting ${syn.SNAPSHOT_FIRST_WEEK}, same rules as generateCalls() in lib/synthetic.ts.
CREATE OR REPLACE TABLE CALLS COMMENT = 'Synthetic call log (no transcript text)' AS
WITH slots AS (
  SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS i FROM TABLE(GENERATOR(ROWCOUNT => ${syn.WEEKS * syn.SLOTS}))
), kept AS (
  SELECT i, FLOOR(i / ${syn.SLOTS}) AS w FROM slots
  WHERE MOD(i, ${syn.SLOTS}) < 170 + SYN_IDX(100000 + FLOOR(i / ${syn.SLOTS}), 1, 60) + 3 * FLOOR(i / ${syn.SLOTS})
), picked AS (
  SELECT i, w, IFF(SYN_IDX(i, 5, 1000) < 50 + 10 * w, ${syn.FEE_TEMPLATE}, SYN_IDX(i, 6, 10)) AS t FROM kept
), shaped AS (
  SELECT i, w, t,
         IFF(SYN_IDX(i, 7, 1000) < 700, ${arr(syn.TEMPLATE_LOB)}[t]::INT, SYN_IDX(i, 8, 5)) AS lob,
         SYN_IDX(i, 12, 1000) < ${arr(syn.TEMPLATE_ESCALATION)}[t]::INT AS escalated,
         SYN_IDX(i, 13, 1000) AS d
  FROM picked
)
SELECT 'CALL-' || LPAD(i, 6, '0') AS CALL_ID,
       DATEADD(day, 7 * w + SYN_IDX(i, 2, 7), '${syn.SNAPSHOT_FIRST_WEEK}'::DATE) AS CALL_DATE,
       TIME_FROM_PARTS(8 + SYN_IDX(i, 3, 10), SYN_IDX(i, 4, 60), 0) AS CALL_TIME,
       ${arr(base)}[t]::INT + SYN_IDX(i, 14, 240) - 60 AS DURATION_SECONDS,
       ${arr(syn.LOBS)}[lob]::VARCHAR AS LINE_OF_BUSINESS,
       ${arr(syn.PRODUCTS)}[ARRAY_CONSTRUCT(${syn.LOB_PRODUCTS.map((p) => arr(p)).join(", ")})[lob][SYN_IDX(i, 9, 2)]::INT]::VARCHAR AS PRODUCT_CATEGORY,
       ${arr(syn.SEGMENTS)}[SYN_IDX(i, 10, 4)]::VARCHAR AS CUSTOMER_SEGMENT,
       ${arr(syn.CALLER_TYPES)}[SYN_IDX(i, 11, 3)]::VARCHAR AS CALLER_TYPE,
       CASE WHEN escalated THEN 'Escalated' WHEN d < 700 THEN 'Resolved' WHEN d < 900 THEN 'Follow-up Required' ELSE 'Transferred' END AS CALL_DISPOSITION,
       t::INT AS TEMPLATE_ID,
       escalated AS ESCALATED
FROM shaped;
${END}`;

const sql = readFileSync(FILE, "utf8");
const a = sql.indexOf(BEGIN);
const b = sql.indexOf(END);
if (a < 0 || b < 0) throw new Error(`markers not found in ${FILE}`);
writeFileSync(FILE, sql.slice(0, a) + block + sql.slice(b + END.length));
console.log(`Updated ${FILE}`);
